def outbreak_sentence(story, post, i, curve):
    key, _, dname, _, _ = story
    v, pv = curve[i], curve[i - 1] if i else 0
    p = PLACE.get(post, "市内")
    if dname in SPECIAL_T:
        if v == 0:
            return None
        phase = {2: 0, 4: 1, 6: 2}.get(v, 3 if pv > v else 1)
        return SPECIAL_T[dname][phase]
    t = rnd.choice
    if v >= 4 and v > pv:
        return t(PEAK_T if v >= 9 else RISE_T).format(p=p, d=dname)
    if v >= 9:
        return t(PEAK_T[2:]).format(p=p, d=dname)
    if pv >= 5 and v < pv * 0.7:
        return t(FALL_T).format(p=p, d=dname)
    return None


