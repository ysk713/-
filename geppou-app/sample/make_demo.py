def season_of(post, mm):
    """その公館の季節（北半球の暦に直す）"""
    if is_south(post):
        mm = (mm + 5) % 12 + 1
    return "winter" if mm in (12, 1, 2) else "spring" if mm in (3, 4, 5) else "summer" if mm in (6, 7, 8) else "autumn"


def poisson(lam):
    """小さな件数のばらつき（ポアソン分布）"""
    if lam <= 0:
        return 0
    L, k, p = pow(2.718281828, -lam), 0, 1.0
    while True:
        p *= rnd.random()
        if p < L:
            return k
        k += 1


