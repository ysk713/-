def officer(spec, m):
    if isinstance(spec, str):
        return spec
    cur = None
    for k in sorted(spec):
        if k <= m:
            cur = spec[k]
    return cur


def season(m, peak, width=1.6):
    """月 m（'2026-07'）が peak 月に近いほど 1 に近づく山形の係数"""
    mi = MONTHS.index(m)
    pi = MONTHS.index(peak) if peak in MONTHS else peak
    return max(0.0, 1 - abs(mi - pi) / width)


