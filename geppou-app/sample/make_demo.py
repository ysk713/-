    if tropical(post) or region in ("アフリカ", "中東"):
        add("旅行者下痢症", size * 0.03)
        add("アメーバ赤痢（腸管感染症）", size * 0.006)
        add("皮膚糸状菌症", size * 0.015)
        add("虫刺症", size * 0.02)
    if post in ("パキスタン", "インド", "バングラデシュ", "ネパール", "アフガニスタン"):
        add("腸チフス", size * 0.006)
        add("A型肝炎", size * 0.003)
    # 犬・猿にかまれた後の狂犬病の予防接種
    if region in RABIES["region"] or post in RABIES["extra"]:
        add("動物咬傷（狂犬病曝露後予防）", size * 0.012)
    # 定期健康診断（年2回の月に集中）・季節の予防接種
    out["健康診断"] = out.get("健康診断", 0) + (round(size * rnd.uniform(0.5, 0.7)) if mm in check_months(idx) else 0)
    vac_months = (4, 5) if is_south(post) else (10, 11)
    if mm in vac_months:
        out["予防接種の必要性"] = out.get("予防接種の必要性", 0) + round(size * rnd.uniform(0.25, 0.4))
    return out


