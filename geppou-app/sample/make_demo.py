def pick_split(names, n):
    """件数 n を表記ゆれの病名に振り分ける"""
    out = {}
    for _ in range(n):
        k = names[0] if rnd.random() < 0.6 else rnd.choice(names)
        out[k] = out.get(k, 0) + 1
    return out


def main():
    reports = {}
    for post, size, spec in POSTS:
        info = posts.INFO[post]
        for m in MONTHS:
            dis = {}
            for names, ratio in BASE:
                n = max(0, round(size * ratio * rnd.uniform(0.75, 1.25)))
                if post in ("オーストラリア", "アルゼンチン", "チリ", "南アフリカ共和国") and names[0].startswith("急性鼻咽頭炎"):
                    n += [0, 1, 3, 5, 6, 4][MONTHS.index(m)]  # 南半球の冬はかぜも増える
                for k, v in pick_split(names, n).items():
                    dis[k] = dis.get(k, 0) + v
            for names, n in story(post, m):
                for k, v in pick_split(names, n).items():
                    dis[k] = dis.get(k, 0) + v
            total = round(sum(dis.values()) * rnd.uniform(0.85, 1.0))
            staff = round(total * 0.48)
            family = round(total * 0.34)
            hei = HEI.get(post, {}).get(m) or ["医療事情に特記事項なし。"]
            reports[f"{m}|{post}"] = {
                "month": m, "post": post, "region": info["region"], "officer": officer(spec, m),
                "staff": staff, "family": family, "other": total - staff - family, "total": total,
                "filename": "デモデータ", "hei": "\n".join(f"{i + 1}. {s}" for i, s in enumerate(hei)),
                "diseases": [{"name": k, "count": v} for k, v in sorted(dis.items(), key=lambda x: -x[1]) if v > 0],
            }
    # 8月は未提出公館を作るため配置表にだけ載せる
    roster = [{"post": p, "officer": officer(spec, "2026-08"), "kana": "", "note": "", "staffed": True} for p, _, spec in POSTS]
    roster += [{"post": p, "officer": o, "kana": "", "note": "", "staffed": True} for p, o in ROSTER_ONLY]
    roster.append({"post": "スーダン", "officer": "", "kana": "", "note": "退避中", "staffed": False})
    demo = {"label": "デモ（架空データ）", "reports": reports, "rosters": {"2026-08": roster}, "overrides": {}, "groups": {}}
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(demo, f, ensure_ascii=False, separators=(",", ":"))
    print(f"{len(reports)} reports, {len(MONTHS)} months -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
